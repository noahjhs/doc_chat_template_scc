#!/usr/bin/env bash
# Builds a standalone macOS .app bundle of the Go rewrite of Casper
# (agent/cmd/casper). Connects out to the self-hosted relay service
# (relay/) instead of bundling cloudflared -- no vendored binary to embed
# anymore. Run from the repo root: ./build/build_go_macos.sh
#
# DEPLOY_ENV=prod (default) or DEPLOY_ENV=dev selects which domains get
# baked in -- e.g. `DEPLOY_ENV=dev ./build/build_go_macos.sh` for a binary
# that can actually pair against the dev environment's auth_service/relay.
# See the DEPLOY_ENV block below for the two file sets this reads from.
#
# Kept alongside build_macos.sh (the Python/PyInstaller build) rather than
# replacing it -- both exist side by side until the Go version is fully
# verified and this repo's distributed binary actually cuts over to it.
set -euo pipefail
cd "$(dirname "$0")/.."

ARCH="$(uname -m)"
if [ "$ARCH" = "arm64" ]; then
    GOARCH="arm64"
else
    GOARCH="amd64"
fi

# DEPLOY_ENV picks which set of repo-root domain files to embed -- "prod"
# (default) reads auth_server.txt/relay_server.txt/app_server.txt, "dev"
# reads the *_server.dev.txt equivalents. Both sets are gitignored,
# untracked, instance-specific files (like .streamlit/secrets.toml), always
# holding a plain bare domain with no scheme. Deliberately two permanent
# files per environment rather than one file temporarily overwritten and
# restored around the build -- that was tried first and rejected: it risked
# leaving the prod files pointed at dev if the build failed partway through
# (a real, silent hazard for the next prod build), and `git checkout` can't
# restore them on a mistake since they're untracked, not just modified.
DEPLOY_ENV="${DEPLOY_ENV:-prod}"
case "$DEPLOY_ENV" in
    prod) SUFFIX="" ;;
    dev)  SUFFIX=".dev" ;;
    *)
        echo "Unknown DEPLOY_ENV '$DEPLOY_ENV' -- expected 'prod' or 'dev'." >&2
        exit 1
        ;;
esac
AUTH_SERVER_FILE="auth_server${SUFFIX}.txt"
RELAY_SERVER_FILE="relay_server${SUFFIX}.txt"
APP_SERVER_FILE="app_server${SUFFIX}.txt"

# Bake in the auth and relay service domains. Unlike app_server*.txt, these
# are NOT optional -- the agent can't sign in or expose itself to the web
# app without them, so catch a missing value here at build time instead of
# at every downloader's first run.
if [ ! -s "$AUTH_SERVER_FILE" ]; then
    echo "$AUTH_SERVER_FILE is missing/empty -- the built binary couldn't sign in. Aborting." >&2
    exit 1
fi
if [ ! -s "$RELAY_SERVER_FILE" ]; then
    echo "$RELAY_SERVER_FILE is missing/empty -- the built binary couldn't expose itself to the web app. Aborting." >&2
    exit 1
fi

# Stage the repo-root source-of-truth files into the Go module's go:embed
# targets. Unlike the PyInstaller build (--add-data + a mktemp staging dir,
# read back at runtime from sys._MEIPASS), go:embed just needs the file to
# exist in the source tree at compile time -- these staged copies are
# regenerated by every build, not committed (see agent/.gitignore).
cp "$AUTH_SERVER_FILE" agent/internal/config/embedded/auth_server.txt
cp "$RELAY_SERVER_FILE" agent/internal/config/embedded/relay_server.txt
if [ -s "$APP_SERVER_FILE" ]; then
    cp "$APP_SERVER_FILE" agent/internal/config/embedded/app_server.txt
else
    echo "$APP_SERVER_FILE is empty/missing — this build won't auto-open the web app."
    : > agent/internal/config/embedded/app_server.txt
fi
if [ -s assets/ghost.png ]; then
    cp assets/ghost.png agent/internal/dialog/assets/ghost.png
else
    echo "assets/ghost.png is missing -- the farewell dialog won't have a custom icon."
    : > agent/internal/dialog/assets/ghost.png
fi

rm -rf build/go_macos_dist
mkdir -p build/go_macos_dist
# CGO_ENABLED=1 (this module's first cgo dependency): the status-bar icon
# (github.com/getlantern/systray) and the casper:// URL-scheme handler
# (internal/urlscheme) both bind Cocoa/AppKit directly. Requires Xcode
# Command Line Tools' clang on the build machine.
( cd agent && GOOS=darwin GOARCH="$GOARCH" CGO_ENABLED=1 go build -o "../build/go_macos_dist/casper-bin" ./cmd/casper )

APP_DIR="dist/CasperGo/Casper.app"
rm -rf "$APP_DIR"
mkdir -p "$APP_DIR/Contents/MacOS" "$APP_DIR/Contents/Resources"

# CFBundleExecutable -- what Finder actually double-click-launches. Runs
# directly, no wrapper: no visible Terminal window. stdout/stderr go nowhere
# when launched this way (same as any ordinary double-clicked Mac app);
# command_log.txt and the native dialogs (farewell, workspace picker) remain
# the user-visible channels, alongside the status-bar icon itself.
cp build/go_macos_dist/casper-bin "$APP_DIR/Contents/MacOS/Casper"
chmod +x "$APP_DIR/Contents/MacOS/Casper"

if [ -s assets/ghost.png ]; then
    ICONSET="build/Casper.iconset"
    rm -rf "$ICONSET"; mkdir -p "$ICONSET"
    for size in 16 32 128 256 512; do
        sips -z $size $size assets/ghost.png --out "$ICONSET/icon_${size}x${size}.png" >/dev/null
        sips -z $((size*2)) $((size*2)) assets/ghost.png --out "$ICONSET/icon_${size}x${size}@2x.png" >/dev/null
    done
    iconutil -c icns "$ICONSET" -o build/Casper.icns
fi

# LSUIElement -- no Dock icon, no Cmd+Tab entry. A reversal of the earlier
# one-shot-tool build (which deliberately showed a Dock icon while it ran in
# the foreground for a single session): Casper is now a persistent
# background daemon whose only UI is its status-bar icon, so a permanently-
# present Dock icon with no window behind it would just be confusing clutter
# for something meant to run quietly as a login item.
#
# CFBundleURLTypes -- registers the casper:// scheme with LaunchServices, so
# a signed-in web app can hand this (already-running, or freshly-launched)
# process a fresh pairing token via casper://pair?token=...&username=...
# (see agent/internal/urlscheme). Confirmed via a throwaway spike that this
# registers reliably for an unsigned bundle like this one, as long as it's
# not sitting in a system staging/temp path (e.g. /private/tmp) -- a normal
# install location (Applications, Desktop, Downloads, etc.) is fine.
cat > "$APP_DIR/Contents/Info.plist" <<PLIST
<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0"><dict>
  <key>CFBundleName</key><string>Casper</string>
  <key>CFBundleDisplayName</key><string>Casper</string>
  <key>CFBundleIdentifier</key><string>com.docchat.casper</string>
  <key>CFBundleExecutable</key><string>Casper</string>
  <key>CFBundlePackageType</key><string>APPL</string>
  <key>CFBundleShortVersionString</key><string>1.0</string>
  <key>CFBundleInfoDictionaryVersion</key><string>6.0</string>
  <key>LSMinimumSystemVersion</key><string>10.13</string>
  <key>LSUIElement</key><true/>
  <key>CFBundleURLTypes</key>
  <array><dict>
    <key>CFBundleURLName</key><string>com.docchat.casper.pair</string>
    <key>CFBundleURLSchemes</key><array><string>casper</string></array>
  </dict></array>
$( [ -f build/Casper.icns ] && echo '  <key>CFBundleIconFile</key><string>Casper.icns</string>' )
</dict></plist>
PLIST

if [ -f build/Casper.icns ]; then
    cp build/Casper.icns "$APP_DIR/Contents/Resources/Casper.icns"
fi

# Ad-hoc code-sign the whole bundle -- confirmed directly this is a real,
# necessary fix, not a nicety: Go's linker already ad-hoc-signs the raw
# executable by itself at link time (a hard requirement for any code to
# run at all on Apple Silicon), but that per-binary signature doesn't cover
# the surrounding bundle (Resources/, Info.plist) added after linking.
# `spctl`/Gatekeeper detects that mismatch on a quarantined (i.e.
# downloaded) copy and rejects it outright as "damaged" -- an unrecoverable
# dead end, not just a warning. Re-signing the *whole* bundle here (after
# every other Contents/ file is in place -- signing has to be the last
# step, since it seals whatever is present at the time) makes it internally
# consistent again (`codesign --verify` passes), which downgrades Gatekeeper's
# reaction to the standard "developer cannot be verified" prompt instead --
# recoverable via right-click "Open" or a System Settings override, the same
# experience most unsigned indie Mac apps already have. This does NOT make
# Gatekeeper (or Chrome's own Safe Browsing download warning) go away
# entirely -- an ad-hoc signature carries no real, Apple-verified identity.
# The full fix (no prompts at all) needs a paid Apple Developer ID
# certificate and notarization, which requires enrolling in Apple's
# Developer Program -- a real account/cost decision, not something this
# script can do on its own.
codesign --force --deep --sign - "$APP_DIR"

cp README_casper.md dist/CasperGo/README.md 2>/dev/null || true
ZIP_NAME="Casper-macos-go${SUFFIX}.zip"
rm -f "dist/$ZIP_NAME"
cd dist
zip -r "$ZIP_NAME" CasperGo
cd ..

# Restore the staged embed targets to empty -- go:embed needs these files to
# exist inside the module tree at compile time (unlike PyInstaller's
# --add-data, which stages from an external mktemp dir untracked files never
# touch), so this is the equivalent of that external-staging safety: nothing
# with real domain/binary content is left sitting in the working tree once
# the build finishes. The built .app already has everything baked in.
: > agent/internal/config/embedded/app_server.txt
: > agent/internal/config/embedded/auth_server.txt
: > agent/internal/config/embedded/relay_server.txt
: > agent/internal/dialog/assets/ghost.png

echo "Built: dist/$ZIP_NAME"
