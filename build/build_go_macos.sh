#!/usr/bin/env bash
# Builds a standalone macOS .app bundle of the Go rewrite of Casper
# (agent/cmd/casper). Connects out to the self-hosted relay service
# (relay/) instead of bundling cloudflared -- no vendored binary to embed
# anymore. Run from the repo root: ./build/build_go_macos.sh
#
# Kept alongside build_macos.sh (the Python/PyInstaller build) rather than
# replacing it -- both exist side by side until the Go version is fully
# verified and this repo's distributed binary actually cuts over to it.
set -euo pipefail
cd "$(dirname "$0")/.."

ARCH="$(uname -m)"
if [ "$ARCH" = "arm64" ]; then
    GOARCH="arm64"
else
    GOARCH="amd64"
fi

# Bake in the auth and relay service domains. Unlike app_server.txt, these
# are NOT optional -- the agent can't sign in or expose itself to the web
# app without them, so catch a missing value here at build time instead of
# at every downloader's first run.
if [ ! -s auth_server.txt ]; then
    echo "auth_server.txt is missing/empty -- the built binary couldn't sign in. Aborting." >&2
    exit 1
fi
if [ ! -s relay_server.txt ]; then
    echo "relay_server.txt is missing/empty -- the built binary couldn't expose itself to the web app. Aborting." >&2
    exit 1
fi

# Stage the repo-root source-of-truth files into the Go module's go:embed
# targets. Unlike the PyInstaller build (--add-data + a mktemp staging dir,
# read back at runtime from sys._MEIPASS), go:embed just needs the file to
# exist in the source tree at compile time -- these staged copies are
# regenerated by every build, not committed (see agent/.gitignore).
cp auth_server.txt agent/internal/config/embedded/auth_server.txt
cp relay_server.txt agent/internal/config/embedded/relay_server.txt
if [ -s app_server.txt ]; then
    cp app_server.txt agent/internal/config/embedded/app_server.txt
else
    echo "app_server.txt is empty/missing — this build won't auto-open the web app."
    : > agent/internal/config/embedded/app_server.txt
fi
if [ -s assets/ghost.png ]; then
    cp assets/ghost.png agent/internal/dialog/assets/ghost.png
else
    echo "assets/ghost.png is missing -- the farewell dialog won't have a custom icon."
    : > agent/internal/dialog/assets/ghost.png
fi

rm -rf build/go_macos_dist
mkdir -p build/go_macos_dist
( cd agent && GOOS=darwin GOARCH="$GOARCH" CGO_ENABLED=0 go build -o "../build/go_macos_dist/casper-bin" ./cmd/casper )

APP_DIR="dist/CasperGo/Casper.app"
rm -rf "$APP_DIR"
mkdir -p "$APP_DIR/Contents/MacOS" "$APP_DIR/Contents/Resources"

# CFBundleExecutable -- what Finder actually double-click-launches. Runs
# directly, no wrapper: no visible Terminal window, and Finder/LaunchServices
# track this exact process under the Casper.app identity for as long as it
# runs, which is what keeps a Dock icon present the whole time it's active --
# no extra plumbing needed for that once nothing hands off to a separate
# app (Terminal) anymore. stdout/stderr go nowhere when launched this way
# (same as any ordinary double-clicked Mac app); status that used to be
# printed (e.g. "Sign in to continue: <url>" if the browser doesn't
# auto-open) has no visible fallback now -- command_log.txt and the native
# dialogs (farewell, workspace picker) remain the user-visible channels.
cp build/go_macos_dist/casper-bin "$APP_DIR/Contents/MacOS/Casper"
chmod +x "$APP_DIR/Contents/MacOS/Casper"

if [ -s assets/ghost.png ]; then
    ICONSET="build/Casper.iconset"
    rm -rf "$ICONSET"; mkdir -p "$ICONSET"
    for size in 16 32 128 256 512; do
        sips -z $size $size assets/ghost.png --out "$ICONSET/icon_${size}x${size}.png" >/dev/null
        sips -z $((size*2)) $((size*2)) assets/ghost.png --out "$ICONSET/icon_${size}x${size}@2x.png" >/dev/null
    done
    iconutil -c icns "$ICONSET" -o build/Casper.icns
fi

cat > "$APP_DIR/Contents/Info.plist" <<PLIST
<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0"><dict>
  <key>CFBundleName</key><string>Casper</string>
  <key>CFBundleDisplayName</key><string>Casper</string>
  <key>CFBundleIdentifier</key><string>com.docchat.casper</string>
  <key>CFBundleExecutable</key><string>Casper</string>
  <key>CFBundlePackageType</key><string>APPL</string>
  <key>CFBundleShortVersionString</key><string>1.0</string>
  <key>CFBundleInfoDictionaryVersion</key><string>6.0</string>
  <key>LSMinimumSystemVersion</key><string>10.13</string>
$( [ -f build/Casper.icns ] && echo '  <key>CFBundleIconFile</key><string>Casper.icns</string>' )
</dict></plist>
PLIST

if [ -f build/Casper.icns ]; then
    cp build/Casper.icns "$APP_DIR/Contents/Resources/Casper.icns"
fi

cp README_casper.md dist/CasperGo/README.md 2>/dev/null || true
rm -f dist/Casper-macos-go.zip
cd dist
zip -r Casper-macos-go.zip CasperGo
cd ..

# Restore the staged embed targets to empty -- go:embed needs these files to
# exist inside the module tree at compile time (unlike PyInstaller's
# --add-data, which stages from an external mktemp dir untracked files never
# touch), so this is the equivalent of that external-staging safety: nothing
# with real domain/binary content is left sitting in the working tree once
# the build finishes. The built .app already has everything baked in.
: > agent/internal/config/embedded/app_server.txt
: > agent/internal/config/embedded/auth_server.txt
: > agent/internal/config/embedded/relay_server.txt
: > agent/internal/dialog/assets/ghost.png

echo "Built: dist/Casper-macos-go.zip"
